import type { GitHubClient, GitHubRepoRef } from "../github/client.js";
import type { AIProvider } from "../types/ai.js";
import type { CopilotConfig } from "../types/config.js";
import { IssueTriageResultSchema, type IssueTriageResult } from "../types/issue.js";
import { sanitizeMarkdown } from "../utils/sanitizer.js";
import { logger } from "../utils/logger.js";

export class IssueTriageAnalyzer {
  constructor(
    private github: GitHubClient,
    private ai: AIProvider,
    public readonly config: CopilotConfig
  ) {}

  async triage(
    ref: GitHubRepoRef,
    issueNumber: number
  ): Promise<{
    result: IssueTriageResult;
    markdown: string;
  }> {
    logger.info(`Fetching issue #${issueNumber} on ${ref.owner}/${ref.repo}...`);
    const issue = await this.github.getIssue(ref, issueNumber);

    const systemPrompt = `You are OSS Copilot, an AI assistant assisting open-source maintainers in triaging incoming repository issues.
Carefully inspect the issue title, user description, and existing context.

Classify the issue into one of these exact types:
- "bug"
- "feature"
- "documentation"
- "question"
- "security"
- "performance"
- "duplicate"
- "other"

Assign:
- priority: "low" | "medium" | "high" | "critical"
- severity: "low" | "medium" | "high" | "critical"
- suggestedLabels: array of clean GitHub label names (e.g. ["bug", "triage/confirmed", "area/auth"])
- summary: 1-2 sentence concise summary of the issue
- maintainerResponse: A polite, professional, and helpful markdown response that a maintainer can post or adapt to address the user.

Output MUST be a JSON object with this shape:
{
  "type": "bug",
  "priority": "medium",
  "severity": "medium",
  "suggestedLabels": ["bug", "needs-repro"],
  "summary": "User reports crash when...",
  "maintainerResponse": "Hi @author, thanks for filing this issue..."
}`;

    const userPrompt = `Issue Number: #${issueNumber}
Title: ${issue.title}
Author: ${issue.user?.login || "anonymous"}
State: ${issue.state}
Existing Labels: ${issue.labels?.map((l: { name?: string } | string) => (typeof l === "string" ? l : l.name || "")).join(", ") || "none"}
Body:
${issue.body || "No description provided."}`;

    logger.info("Classifying and generating triage recommendation...");
    const result = await this.ai.generateStructured<IssueTriageResult>(
      userPrompt,
      systemPrompt,
      (raw) => IssueTriageResultSchema.parse(raw)
    );

    const markdown = this.renderMarkdown(issue.title, issueNumber, result);
    return { result, markdown };
  }

  private renderMarkdown(
    issueTitle: string,
    issueNumber: number,
    result: IssueTriageResult
  ): string {
    let md = `## 🤖 OSS Copilot Issue Triage: #${issueNumber}\n\n`;
    md += `**Issue:** ${issueTitle}\n`;
    md += `**Classification:** \`${result.type}\` | **Priority:** \`${result.priority}\` | **Severity:** \`${result.severity}\`\n\n`;
    md += `### 📝 Summary\n${result.summary}\n\n`;

    if (result.suggestedLabels.length > 0) {
      md += `### 🏷️ Suggested Labels\n`;
      md += result.suggestedLabels.map((lbl) => `\`${lbl}\``).join(" ") + `\n\n`;
    }

    md += `### 💬 Suggested Maintainer Response\n\n`;
    md += `> ${result.maintainerResponse.split("\n").join("\n> ")}\n\n`;
    md += `*Note: This is an automated suggestion generated by [OSS Copilot](https://github.com/pankaj061999/oss-copilot). Maintainers should review before posting.*`;

    return sanitizeMarkdown(md);
  }
}
